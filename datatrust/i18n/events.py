def explain_event(name: str, lang: str) -> Dict[str, Optional[str]]:
    base = name.split(":", 1)[-1] if name.startswith("meta:") else name
    ent = EVENTS.get(base)
    custom = ent is None
    ent = ent or CUSTOM
    pt = lang == "pt-BR"
    return {"label": ent[0] if pt else (base if not custom else "Custom event"),
            "explanation": ent[1] if pt else ent[2], "caveat": ent[3] if pt else ent[4], "custom": custom}
